// Persistent headless session for the explorable world (?mode=explore): loads the page once in headless Chrome
// (GPU, throwaway profile via tools/chrome.mjs), then answers small HTTP calls while it stays open.
//
//   node tools/explore-session.mjs --port 9480 [--w 1440 --h 900] [--params "quality=explore&look=ink"] [--mobile]
//   curl -s localhost:9480/eval -d '{"expr":"window.__explore.stats()"}'
//   curl -s localhost:9480/shot -d '{"out":"out/explore/a.png"}'          screenshot of the page (canvas + UI)
//   curl -s localhost:9480/reload            reload with the latest code       curl -s localhost:9480/quit
//   curl -s localhost:9480/heap -d '{"gc":true}'   the page's V8 heap (Runtime.getHeapUsage, after a full GC when asked)
//   curl -s localhost:9480/cdp -d '{"method":"HeapProfiler.collectGarbage"}'   any DevTools protocol call on the page
//   curl -s localhost:9480/heapprofile -d '{"out":"out/mem/load.heapprofile"}'  the sampling heap profile (with --sample)
//   curl -s localhost:9480/snapshot -d '{"out":"out/mem/load.heapsnapshot"}'      a full heap snapshot (DevTools format)
// --glmem: count the WebGL buffer, texture and renderbuffer bytes the page allocates (window.__glmem(): MB by kind; a
// texture's levels from its storage calls, mipmaps generated by the driver counted as a third of level 0).
// --url http://host:port/path/: open the page there instead of serving this repository (e.g. dist/ from
// tools/build-site.mjs behind any static server).
// --profile: the CPU profiler runs from before the page loads (curl -s localhost:9480/cpuprofile -d '{"out":"x.cpuprofile"}'
// stops it and writes the profile: where the load spent its time).
// --sample [bytes]: sample the page's allocations from before it loads (HeapProfiler.startSampling; the profile keeps
// the samples still alive when it is read: where the live heap was allocated).
// --mobile: a 390 x 844 touch viewport at device scale 3 (phone layout check).
// --novsync: frames are not held to the display's 60 Hz (true frame times for A/B cost checks; fps can exceed 60).
// Holds one GPU-lock slot (out/.gpu.lock.N) like tools/session.mjs; exits after 20 min idle.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startServer } from './serve.mjs';
import { launchChrome, sweepStaleProfiles } from './chrome.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'out');
const args = {};
for (let i = 2; i < process.argv.length; i++) {
  const k = process.argv[i]; if (!k.startsWith('--')) continue;
  const n = process.argv[i + 1]; if (n === undefined || n.startsWith('--')) args[k.slice(2)] = true; else { args[k.slice(2)] = n; i++; }
}
const PORT = Number(args.port || 9480);
const mobile = !!args.mobile;
const W = Number(args.w || (mobile ? 390 : 1440)), H = Number(args.h || (mobile ? 844 : 900));
const IDLE_MS = Number(args.idle || 20) * 60 * 1000;
const SLOTS = Number(process.env.GPU_SLOTS || 4);

let lockPath = null;
async function acquire() {
  for (;;) {
    for (let s = 0; s < SLOTS; s++) {
      const p = path.join(OUT, '.gpu.lock.' + s);
      try {
        const fd = fs.openSync(p, 'wx'); fs.writeSync(fd, JSON.stringify({ pid: process.pid, time: Date.now(), args: 'explore-session ' + PORT })); fs.closeSync(fd);
        lockPath = p; return;
      } catch (e) {
        if (e.code !== 'EEXIST') throw e;
        try { const info = JSON.parse(fs.readFileSync(p, 'utf8')); process.kill(info.pid, 0); } catch { try { fs.rmSync(p, { force: true }); } catch {} }
      }
    }
    await new Promise((r) => setTimeout(r, 1500));
  }
}
function release() { try { if (lockPath) { const i = JSON.parse(fs.readFileSync(lockPath, 'utf8')); if (i.pid === process.pid) fs.rmSync(lockPath, { force: true }); } } catch {} }
process.on('exit', release);
let browser = null;
for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, async () => { release(); if (browser) await browser.cleanup(); process.exit(0); });

fs.mkdirSync(OUT, { recursive: true });
const server = args.url ? { port: 0, close: async () => {} } : await startServer(0);
const pageUrl = (qs) => (args.url ? `${args.url.replace(/\/?$/, '/')}?${qs}` : `http://127.0.0.1:${server.port}/index.html?${qs}`);
await acquire();
sweepStaleProfiles();
const extraArgs = args.novsync ? ['--disable-gpu-vsync', '--disable-frame-rate-limit'] : [];
browser = await launchChrome({ width: Math.max(W, 800), height: Math.max(H, 600), protocolTimeout: 3600 * 1000, extraArgs });
const logs = [];
// WebGL allocation counter (--glmem), installed before the page's scripts run
const GLMEM = `(() => {
  const P = WebGL2RenderingContext.prototype;
  const size = new Map(), kind = new Map(), tot = { buffer: 0, texture: 0, renderbuffer: 0 };
  const set = (o, k, b) => { const old = size.get(o) || 0; size.set(o, b); kind.set(o, k); tot[k] += b - old; };
  const bpp = (gl, f, t) => {
    const T = { [gl.RGBA8]: 4, [gl.SRGB8_ALPHA8]: 4, [gl.RGBA16F]: 8, [gl.RGBA32F]: 16, [gl.R32F]: 4, [gl.R16F]: 2, [gl.RG16F]: 4, [gl.RG32F]: 8,
      [gl.R8]: 1, [gl.RG8]: 2, [gl.RGB8]: 4, [gl.RGB16F]: 8, [gl.RGB32F]: 16, [gl.DEPTH_COMPONENT24]: 4, [gl.DEPTH_COMPONENT32F]: 4, [gl.DEPTH_COMPONENT16]: 2,
      [gl.DEPTH24_STENCIL8]: 4, [gl.DEPTH32F_STENCIL8]: 8, [gl.R11F_G11F_B10F]: 4, [gl.RGB10_A2]: 4, [gl.R8UI]: 1, [gl.R32UI]: 4, [gl.RGBA32UI]: 16, [gl.R16UI]: 2 };
    if (T[f]) return T[f];
    const c = f === gl.RGBA ? 4 : f === gl.RGB ? 4 : f === gl.RED ? 1 : f === gl.RG ? 2 : f === gl.LUMINANCE_ALPHA ? 2 : f === gl.DEPTH_COMPONENT ? 1 : 1;
    const b = t === gl.FLOAT ? 4 : t === gl.HALF_FLOAT ? 2 : t === gl.UNSIGNED_SHORT || t === gl.SHORT ? 2 : t === gl.UNSIGNED_INT || t === gl.INT ? 4 : 1;
    return c * b;
  };
  const bound = new WeakMap();   // gl → { buffer by target, texture by unit/target }
  const st = (gl) => { let s = bound.get(gl); if (!s) bound.set(gl, (s = { buf: new Map(), tex: new Map(), unit: 0, rb: null, lv: new Map() })); return s; };
  const wrap = (name, fn) => { const o = P[name]; P[name] = function (...a) { fn.call(this, st(this), a); return o.apply(this, a); }; };
  wrap('bindBuffer', function (s, [t, b]) { s.buf.set(t, b); });
  wrap('bufferData', function (s, [t, d]) { const b = s.buf.get(t); if (!b) return; set(b, 'buffer', typeof d === 'number' ? d : d ? d.byteLength : 0); });
  wrap('deleteBuffer', function (s, [b]) { if (size.has(b)) { tot[kind.get(b)] -= size.get(b); size.delete(b); } });
  wrap('activeTexture', function (s, [u]) { s.unit = u; });
  wrap('bindTexture', function (s, [t, x]) { s.tex.set(s.unit + ':' + t, x); });
  const texOf = (s, t) => s.tex.get(s.unit + ':' + (t >= this?.TEXTURE_CUBE_MAP_POSITIVE_X && t <= this?.TEXTURE_CUBE_MAP_NEGATIVE_Z ? this.TEXTURE_CUBE_MAP : t));
  const levels = (s, x, key, b) => { let m = s.lv.get(x); if (!m) s.lv.set(x, (m = new Map())); m.set(key, b); let sum = 0; for (const v of m.values()) sum += v; set(x, 'texture', sum); };
  wrap('texStorage2D', function (s, [t, lv, f, w, h]) { const x = s.tex.get(s.unit + ':' + t); if (!x) return; let b = 0; for (let i = 0; i < lv; i++) b += Math.max(1, w >> i) * Math.max(1, h >> i) * bpp(this, f) * (t === this.TEXTURE_CUBE_MAP ? 6 : 1); levels(s, x, 'storage', b); });
  wrap('texStorage3D', function (s, [t, lv, f, w, h, d]) { const x = s.tex.get(s.unit + ':' + t); if (!x) return; let b = 0; for (let i = 0; i < lv; i++) b += Math.max(1, w >> i) * Math.max(1, h >> i) * d * bpp(this, f); levels(s, x, 'storage', b); });
  wrap('texImage2D', function (s, a) {
    let [t, l, f] = a; let w, h, ty;
    if (a.length >= 8) { w = a[3]; h = a[4]; ty = a[7]; } else { const src = a[5]; w = src?.width || src?.videoWidth || 0; h = src?.height || src?.videoHeight || 0; ty = a[4]; }
    const cube = t >= this.TEXTURE_CUBE_MAP_POSITIVE_X && t <= this.TEXTURE_CUBE_MAP_NEGATIVE_Z;
    const x = s.tex.get(s.unit + ':' + (cube ? this.TEXTURE_CUBE_MAP : t)); if (!x) return;
    levels(s, x, t + ':' + l, w * h * bpp(this, f, ty));
  });
  wrap('texImage3D', function (s, [t, l, f, w, h, d, , , ty]) { const x = s.tex.get(s.unit + ':' + t); if (!x) return; levels(s, x, t + ':' + l, w * h * d * bpp(this, f, ty)); });
  wrap('generateMipmap', function (s, [t]) { const x = s.tex.get(s.unit + ':' + t); if (!x) return; const m = s.lv.get(x); if (!m || m.has('storage')) return; const b0 = m.get(t + ':0') || 0; m.set('mips', Math.round(b0 / 3)); let sum = 0; for (const v of m.values()) sum += v; set(x, 'texture', sum); });
  wrap('deleteTexture', function (s, [x]) { if (size.has(x)) { tot.texture -= size.get(x); size.delete(x); s.lv.delete(x); } });
  wrap('bindRenderbuffer', function (s, [t, r]) { s.rb = r; });
  const dims = new Map();
  wrap('renderbufferStorage', function (s, [t, f, w, h]) { if (s.rb) { set(s.rb, 'renderbuffer', w * h * bpp(this, f)); dims.set(s.rb, w + 'x' + h + ':' + f); } });
  wrap('renderbufferStorageMultisample', function (s, [t, n, f, w, h]) { if (s.rb) { set(s.rb, 'renderbuffer', w * h * Math.max(1, n) * bpp(this, f)); dims.set(s.rb, w + 'x' + h + 'x' + n + ':' + f); } });
  wrap('deleteRenderbuffer', function (s, [r]) { if (size.has(r)) { tot.renderbuffer -= size.get(r); size.delete(r); dims.delete(r); } });
  window.__glmem = (detail) => {
    const out = Object.fromEntries(Object.entries(tot).map(([k, v]) => [k, +(v / 1048576).toFixed(1)]));
    if (detail) { const rb = {}; for (const [r, d] of dims) if (size.has(r)) rb[d] = (rb[d] || 0) + 1; out.renderbuffers = rb; }
    return out;
  };
})();`;
let page = null, cdp = null;
async function openPage() {
  if (page) { try { await page.close(); } catch {} }
  page = await browser.newPage();
  cdp = await page.createCDPSession();
  if (args.glmem) await page.evaluateOnNewDocument(GLMEM);
  if (args.profile) { await cdp.send('Profiler.enable'); await cdp.send('Profiler.setSamplingInterval', { interval: 500 }); await cdp.send('Profiler.start'); }
  if (args.sample) {
    await cdp.send('HeapProfiler.enable');
    await cdp.send('HeapProfiler.startSampling', { samplingInterval: Number(args.sample) > 1 ? Number(args.sample) : 65536 });
  }
  await page.setViewport(mobile ? { width: W, height: H, deviceScaleFactor: 3, isMobile: true, hasTouch: true } : { width: W, height: H });
  page.on('console', (m) => { const t = `[page:${m.type()}] ${m.text()}`; logs.push(t); if (logs.length > 600) logs.shift(); if ((m.type() === 'error' || m.type() === 'warning') && !t.includes('Failed to load resource')) console.log(t); });
  page.on('pageerror', (e) => { const t = '[page:error] ' + e.message; logs.push(t); console.log(t); });
}
async function load() {
  await openPage();
  const qs = new URLSearchParams(args.params || '');
  const t0 = Date.now();
  await page.goto(pageUrl(qs), { waitUntil: 'load', timeout: 3600 * 1000 });
  await page.waitForFunction('window.__READY === true || !!window.__RENDER_ERROR', { timeout: 3600 * 1000, polling: 250 });
  const err = await page.evaluate(() => window.__RENDER_ERROR || null);
  if (err) throw new Error(err);
  console.log(`[explore-session] ready in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  return (Date.now() - t0) / 1000;
}
let loadS = await load();
console.log(`[explore-session] page ${pageUrl(new URLSearchParams(args.params || ''))}`);

let last = Date.now();
setInterval(() => { if (Date.now() - last > IDLE_MS) { console.log('[explore-session] idle timeout'); shutdown(); } }, 10000);
async function shutdown() { try { await browser.cleanup(); } catch {} await server.close(); release(); process.exit(0); }

http.createServer(async (req, res) => {
  last = Date.now();
  let body = '';
  for await (const c of req) body += c;
  const send = (code, obj) => { res.writeHead(code, { 'Content-Type': 'application/json' }); res.end(JSON.stringify(obj)); };
  try {
    const cmd = body ? JSON.parse(body) : {};
    if (req.url === '/quit') { send(200, { ok: true }); setTimeout(shutdown, 100); return; }
    if (req.url === '/reload') { if (cmd.params !== undefined) args.params = cmd.params; loadS = await load(); send(200, { ok: true, loadS }); return; }
    if (req.url === '/eval') { const v = await page.evaluate(`(async () => (${cmd.expr}))()`); send(200, { value: v }); return; }
    if (req.url === '/cdp') { send(200, { value: await cdp.send(cmd.method, cmd.params || {}) }); return; }
    if (req.url === '/heap') {
      if (cmd.gc) { await cdp.send('HeapProfiler.collectGarbage'); await cdp.send('HeapProfiler.collectGarbage'); }
      const h = await cdp.send('Runtime.getHeapUsage');
      const mb = (v) => (v === undefined ? undefined : +(v / 1048576).toFixed(1));
      send(200, { usedMB: mb(h.usedSize), totalMB: mb(h.totalSize), embedderMB: mb(h.embedderHeapUsedSize), backingMB: mb(h.backingStorageSize) });
      return;
    }
    if (req.url === '/heapprofile') {
      const { profile } = await cdp.send('HeapProfiler.getSamplingProfile');
      const out = path.resolve(ROOT, cmd.out || 'out/explore/heap.heapprofile');
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, JSON.stringify(profile));
      send(200, { out });
      return;
    }
    if (req.url === '/cpuprofile') {
      const { profile } = await cdp.send('Profiler.stop');
      const out = path.resolve(ROOT, cmd.out || 'out/explore/load.cpuprofile');
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, JSON.stringify(profile));
      send(200, { out });
      return;
    }
    if (req.url === '/snapshot') {
      const out = path.resolve(ROOT, cmd.out || 'out/explore/heap.heapsnapshot');
      fs.mkdirSync(path.dirname(out), { recursive: true });
      const fd = fs.openSync(out, 'w');
      const onChunk = (e) => fs.writeSync(fd, e.chunk);
      cdp.on('HeapProfiler.addHeapSnapshotChunk', onChunk);
      try { await cdp.send('HeapProfiler.takeHeapSnapshot', { reportProgress: false, captureNumericValue: false }); }
      finally { cdp.off('HeapProfiler.addHeapSnapshotChunk', onChunk); fs.closeSync(fd); }
      send(200, { out, MB: +(fs.statSync(out).size / 1048576).toFixed(1) });
      return;
    }
    if (req.url === '/logs') { send(200, { logs: logs.slice(-(cmd.n || 200)) }); return; }
    if (req.url === '/key') { await page.keyboard[cmd.type || 'press'](cmd.key); send(200, { ok: true }); return; }
    if (req.url === '/click') { await page.mouse.click(cmd.x, cmd.y); send(200, { ok: true }); return; }
    if (req.url === '/shot') {
      const out = path.resolve(ROOT, cmd.out || 'out/explore/shot.png');
      fs.mkdirSync(path.dirname(out), { recursive: true });
      await page.screenshot({ path: out, type: 'png' });
      send(200, { out });
      return;
    }
    send(404, { error: 'unknown endpoint' });
  } catch (e) { send(500, { error: String(e.stack || e) }); }
}).listen(PORT, '127.0.0.1', () => console.log(`[explore-session] listening on http://127.0.0.1:${PORT} (load ${loadS.toFixed(1)} s)`));
